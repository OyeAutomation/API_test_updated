"""Built-in universal test suite.

The checks here ALWAYS run for every API, regardless of whether a test case
bank (xlsx) is provided. They are the permanent set of check points built in
W1-W14 of the framework rollout:

  W1  - contract evaluation (DEFECT detection)          W8  - security headers
  W2  - archetype-driven selection                      W9  - CORS
  W3  - baseline assertion                              W10 - sensitive data scan
  W4  - query-param validation/injection                W11 - error leak scan
  W5  - method change                                   W12 - response schema
  W6  - mass assignment                                 W13 - SLA / performance
  W7  - NoSQL injection                                 W14 - duplicate submit

When a test case bank is supplied, its rows are merged in and deduped by
test_case_id — the built-in entries win, so these checks can never be removed
or disabled through the bank.
"""

from typing import List

from src.models import (
    MutationType,
    TestCase,
    TestCaseScope,
    TestCaseType,
)


def _tc(
    test_case_id: str,
    scope: TestCaseScope,
    test_case_type: TestCaseType,
    description: str,
    mutation_type: MutationType,
    mutation_value: str = "",
    expected_range: str = "",
    expected_behavior: str = "",
    mandatory_only: bool = False,
) -> TestCase:
    return TestCase(
        test_case_id=test_case_id,
        scope=scope,
        test_case_type=test_case_type,
        description=description,
        mutation_type=mutation_type,
        mutation_value=mutation_value or None,
        expected_status_code_range=expected_range or None,
        expected_behavior=expected_behavior,
        applies_to_mandatory_only=mandatory_only,
        enabled=True,
    )


